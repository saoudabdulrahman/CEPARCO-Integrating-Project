; Extract BGR channels from exactly 24 bytes (eight pixels).
; RCX=source, RDX=red, R8=green, R9=blue.

bits 64
default rel

section .rdata align=16
align 16
b_first: db 0,3,6,9,12,15,0x80,0x80, 0x80,0x80,0x80,0x80,0x80,0x80,0x80,0x80
align 16
b_last:  db 0x80,0x80,0x80,0x80,0x80,0x80,2,5, 0x80,0x80,0x80,0x80,0x80,0x80,0x80,0x80
align 16
g_first: db 1,4,7,10,13,0x80,0x80,0x80, 0x80,0x80,0x80,0x80,0x80,0x80,0x80,0x80
align 16
g_last:  db 0x80,0x80,0x80,0x80,0x80,0,3,6, 0x80,0x80,0x80,0x80,0x80,0x80,0x80,0x80
align 16
r_first: db 2,5,8,11,14,0x80,0x80,0x80, 0x80,0x80,0x80,0x80,0x80,0x80,0x80,0x80
align 16
r_last:  db 0x80,0x80,0x80,0x80,0x80,1,4,7, 0x80,0x80,0x80,0x80,0x80,0x80,0x80,0x80

section .text
    global packed_bgr8_extract
packed_bgr8_extract:
    vmovdqu xmm0, [rcx]
    vmovq   xmm1, [rcx + 16]

    ; Red channel.
    vpshufb xmm2, xmm0, [r_first]
    vpshufb xmm3, xmm1, [r_last]
    vpor    xmm2, xmm2, xmm3
    vpmovzxbd ymm2, xmm2
    vcvtdq2ps ymm2, ymm2
    vmovups [rdx], ymm2

    ; Green channel.
    vpshufb xmm2, xmm0, [g_first]
    vpshufb xmm3, xmm1, [g_last]
    vpor    xmm2, xmm2, xmm3
    vpmovzxbd ymm2, xmm2
    vcvtdq2ps ymm2, ymm2
    vmovups [r8], ymm2

    ; Blue channel.
    vpshufb xmm2, xmm0, [b_first]
    vpshufb xmm3, xmm1, [b_last]
    vpor    xmm2, xmm2, xmm3
    vpmovzxbd ymm2, xmm2
    vcvtdq2ps ymm2, ymm2
    vmovups [r9], ymm2

    vzeroupper
    ret
